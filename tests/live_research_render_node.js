const assert=require('node:assert/strict');
require('../qf/web/native-live-research.js');
const tool=QfNativeLiveResearch;
let applies=[],installs=0;
const layer={apply:p=>{applies.push(p);return true;},dispose(){}};
const chart={};
const live=tool.attach(chart,{run_id:'r',generation:7,layer,install:()=>installs++});
const row={time_ns:'100',end_ns:'200',close:10};
const snapshot={run_id:'r',revision:1,as_of_ns:'150',bars:[row],fills:[],risk_events:[],ma_series:[]};
assert.equal(live.apply(snapshot),true);assert.equal(live.apply(snapshot),false);
assert.equal(live.apply({...snapshot,revision:2,bars:[{...row,time_ns:'160'}]}),false);
assert.equal(live.apply({...snapshot,revision:2,run_id:'wrong'}),false);
assert.equal(live.apply({...snapshot,revision:2,fills:[{time_ns:'151'}]}),false);
assert.equal(live.apply({...snapshot,revision:2,ma_series:[{points:[{time_ns:'151'}]}]}),false);
assert.equal(live.apply({...snapshot,revision:2,bars:[{...row,close:11}]}),true);
assert.equal(installs,2);assert.equal(applies[1].revision,7);assert.equal(applies[1].bars[0].close,11);
const base={source:1,origin:'http://127.0.0.1',data:{run_id:'r',generation:7}};
assert.equal(tool.acceptMessage(base,1,base.origin,'r',7),true);
assert.equal(tool.acceptMessage({...base,source:2},1,base.origin,'r',7),false);
assert.equal(tool.acceptMessage({...base,origin:'http://evil'},1,base.origin,'r',7),false);
assert.equal(tool.acceptMessage({...base,data:{run_id:'r',generation:8}},1,base.origin,'r',7),false);
live.dispose();assert.equal(live.apply({...snapshot,revision:3}),false);
const rolling=tool.attach(chart,{run_id:'r',generation:8,layer,install:()=>{}});
const bars=Array.from({length:500},(_,i)=>({time_ns:String(i+100),end_ns:String(i+101),close:i}));
assert.equal(rolling.apply({...snapshot,revision:1,as_of_ns:'700',first_bar_id:100,bars}),true);
assert.equal(applies.at(-1).first_bar_id,100);assert.equal(applies.at(-1).bars.length,500);
rolling.dispose();
console.log('LIVE_RESEARCH_RENDER_OK');
