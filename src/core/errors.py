"""异常类型 —— 与 R32 的五类故障处置方式一一对应。

R32.2 要求「处置方式可由异常类型确定」。所以捕获方不需要读抛出点的上下文,
只看类型就知道该停机、该停策略、该回灌、该重试,还是该计数跳过。

不分类的后果是二者之一:系统因琐事崩掉,或带着严重故障继续交易。**后者会亏钱。**

层级:

    QfError
    ├─ HaltRequired        立即停机 + 推手机 + 人工放行,绝不自动恢复(R32.3)
    ├─ StrategyFailure     停该策略实例,其余继续(R32.4)
    ├─ Rejected            拒绝当前操作并回灌策略(R32.5)
    ├─ Retryable           有界重试,超上限升级(R32.6/R32.8)
    └─ Skipped             记录并跳过,计数型汇总而非逐条告警(R32.7)
"""

__all__ = [
    "CalendarMissing",
    "CompliancePreflightFailed",
    "ConfigInvalid",
    "HaltRequired",
    "InsufficientFunds",
    "NotInTradingSession",
    "PriceLimitBlocked",
    "QfError",
    "ReconcileMismatch",
    "Rejected",
    "RetriesExhausted",
    "Retryable",
    "RiskCheckFailed",
    "RiskVetoed",
    "SessionSpecMissing",
    "Skipped",
    "StrategyFailure",
    "SymbolAmbiguous",
]


class QfError(Exception):
    """本系统全部自有异常的根类。"""


# --------------------------------------------------------------------------
# 第一类:需立即停机并等待人工放行(R32.3)
# --------------------------------------------------------------------------


class HaltRequired(QfError):
    """使系统进入 Halt_State。

    Halt_State 下拒绝全部开仓委托,允许平仓与撤单通过(R18.12)。
    系统不自行退出该状态(R18.11),只能由人工放行指令解除(R18.13)。
    """


class ReconcileMismatch(HaltRequired):
    """本地持仓/资金/委托与期货公司返回结果不符(R18.10)。

    最危险的场景是「报单已发、回报未收」时断线:本地记空仓、券商记多 2 手。
    **绝不自动纠正** —— 自动以某一侧覆盖另一侧,会把一次可发现的不一致
    变成一个静默的错误持仓(ADR-0009)。
    """


class CompliancePreflightFailed(HaltRequired):
    """穿透式监管前置检查未通过(R1.2)。

    典型失效是 AppID/AuthCode 为空或采集库缺失。若不做前置检查,表现为
    CTP 登录被拒且错误码不直观,而且通常在 20:59 才发现。
    """


class RiskCheckFailed(HaltRequired):
    """风控模块自身抛出异常(R19.18)。

    此时不得以「校验通过」作为默认结论 —— 风控失效意味着无保护地交易。
    """


class CalendarMissing(HaltRequired):
    """请求的日期超出交易日历数据覆盖范围(R3.13)。

    抛错而非返回推测结果:猜错交易日会使日线聚合、单日亏损限额、结算 PnL
    全部静默出错,而 1 分钟 Bar 看起来完全正常。
    """


class ConfigInvalid(QfError):
    """必填配置项缺失或数值越界(R22.8)。

    发生在启动阶段而非运行期,故不归入 Halt_State —— 直接终止启动流程。
    """


# --------------------------------------------------------------------------
# 第二类:需停止单个策略实例(R32.4)
# --------------------------------------------------------------------------


class StrategyFailure(QfError):
    """某策略实例的回调抛出异常(R11.15)。

    停该实例并记录堆栈,其他实例继续运行。
    """


# --------------------------------------------------------------------------
# 第三类:需拒绝当前操作并通知策略(R32.5)
# --------------------------------------------------------------------------


class Rejected(QfError):
    """拒绝一笔委托意图,且该结果必须回灌给策略(R17.13)。

    必须回灌的理由见 D2:策略以为开了仓、实际被拒,内部状态就与真实持仓
    发散,下根 K 线会继续重试。以目标持仓表达意图(ADR-0003)使这里天然收敛
    —— 目标没变,执行层下根 Bar 继续尝试。
    """

    def __init__(self, reason: str) -> None:
        super().__init__(reason)
        self.reason = reason


class RiskVetoed(Rejected):
    """风控否决(R19.17)。"""


class InsufficientFunds(Rejected):
    """预估保证金与手续费之和超过可用资金(R19.3)。"""


class PriceLimitBlocked(Rejected):
    """委托价格超出当日涨跌停区间(R19.9)。"""


# --------------------------------------------------------------------------
# 第四类:需有界重试(R32.6)
# --------------------------------------------------------------------------


class Retryable(QfError):
    """可重试的暂态故障:写库失败、CTP 查询超时、行情连接中断。

    **必须有上限。** 无上界重试在写库持续失败(磁盘满、锁表)时会让内存缓冲
    无限增长 → OOM → 全部丢失(D4)。上限由配置项给出,超限后落地兜底文件。
    """


class RetriesExhausted(HaltRequired):
    """重试次数达到上限,故障已升级(R32.8)。

    继承 HaltRequired:有界重试的终点必须是停机或停策略,不能是静默放弃。
    """


# --------------------------------------------------------------------------
# 第五类:仅记录并跳过(R32.7)
# --------------------------------------------------------------------------


class Skipped(QfError):
    """单条记录级别的问题:Tick 时间戳越界、外部数据源单条记录字段缺失。

    以计数形式汇总,不逐条发布告警事件 —— 全市场录制下冷门与远月合约会
    产生大量此类记录,逐条告警会把真正的告警淹没(D1)。
    """


class NotInTradingSession(Skipped):
    """时间戳不落在该合约的任何 Trading_Session 内(R3.10)。

    归入 Skipped 而非 HaltRequired 是刻意的:盘前盘后、集合竞价与节假日的越界
    时间戳是**常态而非故障**,全市场录制下每天会命中大量此类时间戳。若按停机类
    处理,第一次收到 08:59 的行情就会冻结整个系统(D1)。

    调用方按 R3.10 丢弃该 Tick 并计入计数型日志。区别于 CalendarMissing:后者是
    「日历数据没覆盖到这一天」,属需人工放行的数据缺陷,不会自行恢复。
    """


class SessionSpecMissing(Skipped):
    """某品种在参考日期上没有生效的时段定义(R3.3/R32.7)。

    归入 Skipped 而非 HaltRequired:缺的是**一个品种**的配置,不是整份日历。若按停机
    处理,录制器收到一个未配置品种的行情就会冻结全部品种 —— 用一个品种的配置遗漏
    换全市场的数据损失,而自录 tick 丢了买不回来。

    **跳过不等于无声**:被跳过的行情无法事后补录,调用方必须按品种汇总计数并发布
    需人工关注类告警(R32.7)。与 CalendarMissing 的分工:后者表示请求日期超出日历
    覆盖,所有品种都无法判定,仍属停机类。
    """


class SymbolAmbiguous(QfError):
    """郑商所 3 位年月码在给定参考日期下对应多个有效合约(R27.5)。

    输出错误而非返回任一推断结果:`MA509` 是 2015 还是 2025 猜错时不报错、
    数据还能对上,是典型的静默错配。
    """
