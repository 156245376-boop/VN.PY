'use strict';
const assert=require('node:assert/strict');
global.window=global;
require('../qf/web/chart-state.js');
let s=QfChartState.defaults();
assert.deepEqual(QfChartState.visibleIds(s),['pane-1']);
s=QfChartState.reduce(s,{type:'activate',id:'pane-3'});
s=QfChartState.reduce(s,{type:'layout',value:'columns'});
assert.deepEqual(QfChartState.visibleIds(s),['pane-3','pane-1']);
s=QfChartState.reduce(s,{type:'activate',id:'pane-1'});
assert.deepEqual(QfChartState.visibleIds(s),['pane-3','pane-1']);
s=QfChartState.reduce(s,{type:'choose',symbol:'KQ.m@SHFE.rb'});
assert.equal(s.panes[1].continuous,'KQ.m@SHFE.rb');
const before=JSON.stringify(s.panes);
s=QfChartState.reduce(s,{type:'link',value:true});
assert.equal(JSON.stringify(s.panes),before);
s=QfChartState.reduce(s,{type:'choose',symbol:'KQ.m@DCE.m'});
assert.equal(s.panes[0].continuous,'KQ.m@DCE.m');
assert.equal(s.panes[1].continuous,'KQ.m@DCE.m');
assert.equal(s.panes[2].continuous,null);
assert.equal(QfChartState.period({mode:'continuous',period:null}),'1d');
assert.equal(QfChartState.duration('1h'),3600000000000);
console.log('CHART_STATE_OK');
